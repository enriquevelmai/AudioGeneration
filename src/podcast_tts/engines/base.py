"""Common interface of the TTS engines and license metadata."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import TYPE_CHECKING, Any, Protocol, Union, runtime_checkable

import numpy as np

if TYPE_CHECKING:
    from ..voices import Voice

__all__ = [
    "COMMERCIAL_DEPENDS",
    "EngineError",
    "LicenseInfo",
    "TTSEngine",
    "UNKNOWN_LICENSE",
    "engine_cache_tag",
    "package_version",
]

#: Value of ``LicenseInfo.commercial_use`` when it depends on the plan purchased from the provider.
COMMERCIAL_DEPENDS = "depends on plan"

CommercialUse = Union[bool, str]


class EngineError(RuntimeError):
    """Error from a TTS engine (model not available, incompatible voice, API down...)."""


@dataclass(frozen=True)
class LicenseInfo:
    """License that governs the audio generated by an engine (model or service).

    - ``name``: short name ("CC-BY-NC-4.0", "Coqui Public Model License"...).
    - ``url``: where to read the license or the terms.
    - ``commercial_use``: ``True``, ``False`` or ``"depends on plan"``.
    - ``notes``: short clarifications.
    """

    name: str
    url: str = ""
    commercial_use: CommercialUse = False
    notes: str = ""

    @property
    def is_non_commercial(self) -> bool:
        """``True`` only if the license explicitly forbids commercial use."""
        return self.commercial_use is False

    def commercial_label(self) -> str:
        """Short text for tables: "yes", "no" or "depends on plan"."""
        if self.commercial_use is True:
            return "yes"
        if self.commercial_use is False:
            return "no"
        return str(self.commercial_use)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


#: License assumed for third-party engines that do not declare ``license_info``.
UNKNOWN_LICENSE = LicenseInfo(
    name="not declared",
    url="",
    commercial_use=False,
    notes="The engine does not declare its license: treat it as non-commercial until you check.",
)


def package_version(dist: str) -> str:
    """Installed version of the ``dist`` package (``""`` if it is not installed)."""
    from importlib import metadata

    try:
        return metadata.version(dist)
    except metadata.PackageNotFoundError:
        return ""


def engine_cache_tag(engine: Any) -> str:
    """The engine's ``cache_tag`` (attribute, property or no-argument method); ``""`` if none."""
    tag = getattr(engine, "cache_tag", "")
    if callable(tag):
        tag = tag()
    return str(tag or "")


@runtime_checkable
class TTSEngine(Protocol):
    """Protocol implemented by every engine (built-in and third-party).

    Class attributes:

    - ``name``: short identifier ("f5", "xtts", "openai"...).
    - ``license_info``: :class:`LicenseInfo` of the model or service.
    - ``kind`` (optional, default ``"local"``): ``"local"`` or ``"cloud"``.
    - ``required_config`` (optional, default ``()``): required configuration
      variables (e.g. ``("OPENAI_API_KEY",)``), read through :mod:`podcast_tts.config`.
    - ``cache_tag`` (optional, text or property): identifies the model, its version and the
      parameters that change the audio. It is part of the synthesis cache key, so
      changing it causes the sentences to be synthesized again (see
      :func:`engine_cache_tag`).

    Methods:

    - ``sample_rate``: sample rate of the returned audio.
    - ``synthesize``: returns a float32 mono ``np.ndarray`` in [-1, 1] at
      ``sample_rate`` Hz. ``lang`` is a short ISO code ("es", "en"...) and
      ``speed`` a factor (1.0 = normal). The voice provides ``ref_wav``,
      ``ref_text``, ``xtts_speaker``, ``provider_voice_id`` and ``provider_options``.
    """

    name: str
    license_info: LicenseInfo

    @property
    def sample_rate(self) -> int: ...

    def synthesize(self, text: str, voice: "Voice", lang: str, speed: float = 1.0) -> np.ndarray: ...
